import type { Cell, MapSpec } from '../../sim';

// Gem TD+'s field for player 1 (docs/research/gem-td-rules.md §2), one 64-unit
// cell per character, row 0 at the north edge. A gem, Rock or special covers
// 2 × 2 cells and its anchor snaps to the 64-unit grid, so gems can sit half a
// gem apart (assumed: WC3 build squares are 64 units; nvs/gem doesn't say).
//
// Assumed, as in the reference:
// - Everything outside the 95 × 71 box is wall. In WC3 single player the land
//   west and south of the box is open, so creeps could detour there.
// - A cell is unwalkable if any of its four 32-unit pathing cells is, and
//   buildable only if all four are buildable and inside the build rect.
// - Two footprints touching only at a corner block the gap (the core never cuts corners).

/** The 64-unit cell grid's left (west) and top (north) edges in WC3 coordinates. */
export const GEM_ORIGIN_WC3 = { minX: -6208, maxY: 8960 } as const;

/**
 * Where WC3's spawn, checkpoint and exit points fall: each marks the corner
 * shared by four cells, and the trigger is a 64 × 64 square centred on it, so a
 * checkpoint region is those four cells (assumed: entering any of them counts).
 */
function corner(col: number, row: number): Cell[] {
  return [[col - 1, row], [col, row], [col - 1, row + 1], [col, row + 1]];
}

